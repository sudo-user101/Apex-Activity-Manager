import AppKit

/// One thing that was copied.
struct ClipItem: Identifiable, Hashable {
    enum Kind: Hashable { case text(String), files([URL]), image(NSImage) }
    let id = UUID()
    let kind: Kind
    let date: Date
    let app: String          // the app that was in front when it was copied

    var preview: String {
        switch kind {
        case .text(let s): return s.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\n", with: " ⏎ ")
        case .files(let u): return u.count == 1 ? u[0].lastPathComponent : "\(u.count) files: " + u.map(\.lastPathComponent).joined(separator: ", ")
        case .image(let i): return "Image · \(Int(i.size.width)) × \(Int(i.size.height))"
        }
    }
    var symbol: String {
        switch kind { case .text: return "text.alignleft"; case .files: return "doc"; case .image: return "photo" }
    }
}

/// What was copied recently (newest first, 50 items). Checks the pasteboard's
/// change count twice a second, which costs next to nothing. Items marked
/// concealed or temporary (passwords from password managers, one-time codes)
/// are never kept, and the history lives in memory only: it's gone when Apex
/// quits.
@MainActor @Observable
final class ClipboardHistory {
    static let shared = ClipboardHistory()
    static let limit = 50
    static let maxImageBytes = 8 << 20

    private(set) var items: [ClipItem] = []
    var enabled: Bool = UserDefaults.standard.object(forKey: "clipboardHistory") as? Bool ?? true {
        didSet {
            UserDefaults.standard.set(enabled, forKey: "clipboardHistory")
            if enabled { start() } else { timer?.invalidate(); timer = nil; items.removeAll() }
        }
    }

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var ownChange = -1

    /// Pasteboard types apps use to say "don't record this" (nspasteboard.org).
    nonisolated static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    func start() {
        guard enabled, timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardHistory.shared.check() }
        }
        timer?.tolerance = 0.25
    }

    private func check() {
        let pb = NSPasteboard.general
        let change = pb.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard change != ownChange else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName ?? ""
        let item: ClipItem?
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            item = ClipItem(kind: .files(urls), date: Date(), app: app)
        } else if let s = pb.string(forType: .string), !s.isEmpty {
            item = ClipItem(kind: .text(String(s.prefix(20_000))), date: Date(), app: app)
        } else if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), data.count <= Self.maxImageBytes,
                  let img = NSImage(data: data) {
            item = ClipItem(kind: .image(img), date: Date(), app: app)
        } else {
            item = nil
        }
        guard let item else { return }
        // The same thing copied again moves to the top instead of repeating.
        items.removeAll { $0.kind == item.kind }
        items.insert(item, at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    /// Puts an item back on the clipboard (it moves to the top).
    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text(let s): pb.setString(s, forType: .string)
        case .files(let u): pb.writeObjects(u as [NSURL])
        case .image(let i): pb.writeObjects([i])
        }
        ownChange = pb.changeCount
        lastChange = ownChange
        items.removeAll { $0.id == item.id }
        items.insert(ClipItem(kind: item.kind, date: Date(), app: item.app), at: 0)
    }

    func remove(_ item: ClipItem) { items.removeAll { $0.id == item.id } }
    func clear() { items.removeAll() }
}
